/// PNG 1 × 1 transparan untuk foto tiruan.
final transparentPng = Uint8List.fromList(const [
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, //
  0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, //
  0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00, //
  0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, //
  0x42, 0x60, 0x82,
]);

/// Cache foto KTA tiruan: mencatat permintaan foto dan pengosongan tanpa plugin cache.
class RecordingAvatarCache extends KtaAvatarCache {
  RecordingAvatarCache() : super(MemorySecureStore(), createManager: () => throw StateError('tidak dipakai di uji'));

  final List<({String url, String? cacheKey})> requests = [];
  int clears = 0;

  @override
  ImageProvider imageFor(String url, {String? cacheKey}) {
    requests.add((url: url, cacheKey: cacheKey));
    return MemoryImage(transparentPng);
  }

  @override
  Future<void> clear() async => clears++;
}
